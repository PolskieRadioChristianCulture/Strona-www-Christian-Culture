function renderCatalogCardSsr(rec, lang) {
  const isEn = lang === 'en';
  const name = isEn ? rec.name_en : rec.name;
  const cat = isEn ? rec.category_en : rec.category;
  const country = isEn ? rec.country_en : rec.country;
  const desc = isEn ? rec.description_en : rec.description_pl;
  const loc = rec.address ? `${rec.city}, ${rec.address}` : `${rec.city || ''} · ${country}`;
  const href = isEn ? `${BASE}/en/institution/${rec.slug}/` : `${BASE}/instytucja/${rec.slug}/`;
  const extHref = rec.website || rec.source;
  const extLabel = isEn ? (rec.website ? 'Official site' : 'Source ↗') : (rec.website ? 'Strona www' : 'Odwiedź źródło ↗');

  return `<article class="inst-card" data-slug="${esc(rec.slug)}">
  <div>
    <div class="card-badges">
      <span class="badge-cat">${esc(cat)}</span>
      <span class="badge-trust">${esc(country)}</span>
    </div>
    <h3 class="card-title"><a href="${esc(href)}">${esc(name)}</a></h3>
    <div class="card-loc">${esc(loc)}</div>
    <p class="card-desc">${esc(desc)}</p>
  </div>
  <div class="card-foot">
    <a class="card-link-profile" href="${esc(href)}">${isEn ? 'View profile →' : 'Zobacz profil →'}</a>
    ${extHref ? `<a class="card-link-ext" href="${esc(extHref)}" target="_blank" rel="noopener noreferrer">${esc(extLabel)}</a>` : ''}
  </div>
</article>`;
}

