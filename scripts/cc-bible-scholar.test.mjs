test('Scholar Tools [Strong]: Greek G3056, Hebrew H7225 RTL, and STEP autoGenerated separation', async () => {
  resetScholarToolsCache();

  const gRes = await ccBibleLexiconLookup({ strongId: 'G3056' });
  assert.equal(gRes.found, true);
  assert.equal(gRes.entry.strong, 'G3056');
  assert.equal(gRes.entry.original, 'λόγος');
  assert.equal(gRes.entry.strongTier, 'classic_strongs');
  assert.equal(gRes.entry.autoGenerated, false);
  assert.equal(gRes.entry.dir, 'ltr');
  assert.equal(gRes.datasetId, 'step-mojabiblia-interlinear');
  assert.equal(gRes.licenseId, 'CC-BY-4.0');

  const hRes = await ccBibleLexiconLookup({ strongId: 'H7225' });
  assert.equal(hRes.found, true);
  assert.equal(hRes.entry.dir, 'rtl');
  assert.equal(hRes.entry.strongTier, 'classic_strongs');

  // Extended STEP Strong ID check on real G.json if present
  const gDict = await loadScholarAsset('data/bible/lexicon/G.json');
  const extKey = Object.keys(gDict).find((k) => gDict[k]?.autoGenerated || /^G(21[5-9]\d{2}|2[2-9]\d{3}|[3-9]\d{4})/.test(k));
  if (extKey) {
    const extRes = await ccBibleLexiconLookup({ strongId: extKey });
    assert.equal(extRes.found, true);
    assert.equal(extRes.entry.strongTier, 'step_extended');
    assert.equal(extRes.entry.autoGenerated, true);
    assert.ok(extRes.uncertaintyNotice);
  }
});

