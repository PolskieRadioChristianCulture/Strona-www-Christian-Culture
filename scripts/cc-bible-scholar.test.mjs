test('MCP Permission & License Enforcement + Path Traversal / Security guards', async () => {
  assert.equal(sanitizeDataAssetPath('../secrets.json'), null);
  assert.equal(sanitizeDataAssetPath('data\\bible\\GEN_01.json'), null);
  assert.equal(sanitizeDataAssetPath('serviceAccountKey.json'), null);
  assert.equal(sanitizeDataAssetPath('data/bible-scholar/xrefs/GEN.json'), 'data/bible-scholar/xrefs/GEN.json');

  // Active plugin filter denies uninstalled Scholar plugin tool
  const denied = isToolAllowedForSession('cc_bible_cross_references', ['scroll-bible']);
  assert.equal(denied.allowed, false);
  assert.equal(denied.code, 'PLUGIN_NOT_INSTALLED');

  const mcpDenyRes = await handleAiDlaJezusaApi(new Request('https://polskieradio.cc/api/ai-dla-jezusa/v1/mcp', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-CC-Active-Plugins': 'scroll-bible'
    },
    body: JSON.stringify({
      jsonrpc: '2.0',
      id: 10,
      method: 'tools/call',
      params: { name: 'cc_bible_cross_references', arguments: { reference: 'J 3:16' } }
    })
  }));
  const mcpDenyJson = await mcpDenyRes.json();
  assert.ok(mcpDenyJson.error);
  assert.match(mcpDenyJson.error.message, /PLUGIN_NOT_INSTALLED/);

  // Allowed when active
  const mcpAllowRes = await handleAiDlaJezusaApi(new Request('https://polskieradio.cc/api/ai-dla-jezusa/v1/mcp', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-CC-Active-Plugins': 'cross-references'
    },
    body: JSON.stringify({
      jsonrpc: '2.0',
      id: 11,
      method: 'tools/call',
      params: { name: 'cc_bible_cross_references', arguments: { reference: 'J 3:16', limit: 3 } }
    })
  }));
  const mcpAllowJson = await mcpAllowRes.json();
  const textOut = mcpAllowJson.result?.content?.[0]?.text || '';
  assert.match(textOut, /openbible-cross-references/);
});

test('Offline Study Methods & AI Chat / LumiMes work without AI keys (ZERO COST)', async () => {
  resetAiChatRuntimeState();
  const q6 = await ccBibleStudyQuestions({ method: 'six-questions', reference: 'Flp 4:6' });
  assert.equal(q6.found, true);
  assert.equal(q6.questions.length, 6);

  const seed = await ccBibleMindMapSeed({ reference: 'Rz 8:28' });
  assert.equal(seed.found, true);
  assert.ok(seed.mindMap.nodes.length >= 4);

  const chatRes = await processAiChat({
    message: 'Wyjaśnij G3056 oraz pokaż odsyłacze dla J 3:16',
    activePlugins: ['strongs', 'cross-references']
  }, {}, {});
  assert.equal(chatRes.ok, true);
  assert.equal(chatRes.zeroCostGuaranteed, true);
  assert.ok(chatRes.toolsUsed.includes('cc_bible_lexicon_lookup'));
  assert.ok(chatRes.toolsUsed.includes('cc_bible_cross_references'));
  assert.match(chatRes.reply, /G3056/);

  const lumiRes = await processLumiChat({
    assistantId: 'rut',
    message: 'Pokaż odsyłacze dla tego wersetu',
    context: { bible: { book: 'JHN', chapter: 3, verseStart: 16 } },
    activePlugins: ['cross-references']
  }, {}, {});
  assert.equal(lumiRes.ok, true);
  assert.equal(lumiRes.zeroCostGuaranteed, true);
  assert.ok(lumiRes.toolsUsed.includes('cc_bible_cross_references'));
  assert.ok(lumiRes.actions.some((a) => a.url.includes('/sba/studium/')));
});

