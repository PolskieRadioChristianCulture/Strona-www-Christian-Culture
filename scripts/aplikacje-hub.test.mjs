// Kontrakt testowy Centrum Aplikacji Christian Culture (/test/aplikacje/ PL & EN).
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { isPublicFile } from './cc-release-files.mjs';
import { buildAll, PLAY_APP_PL, PLAY_APP_EN, PLAY_DEV_PL, PLAY_DEV_EN } from './aplikacje/buduj.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');

const plHtml = read('test/aplikacje/index.html');
const enHtml = read('test/aplikacje/en/index.html');
const apCss = read('test/aplikacje/ap.css');
const apJs = read('test/aplikacje/ap.js');
const apEcoJs = read('test/aplikacje/ap-eco.js');

const ecoBox = { module: { exports: {} } };
vm.runInNewContext(apEcoJs, ecoBox);
const eco = ecoBox.module.exports;

test('jedno źródło prawdy: generator buduj.mjs daje wynik 1:1 z test/aplikacje', () => {
  const generated = buildAll(false);
  assert.equal(plHtml, generated.plHtml);
  assert.equal(enHtml, generated.enHtml);
  assert.match(plHtml, /^<!-- GENERATED BY scripts\/aplikacje\/buduj\.mjs/);
  assert.match(enHtml, /^<!-- GENERATED BY scripts\/aplikacje\/buduj\.mjs/);
});

test('wersja testowa ma noindex,nofollow oraz komplet SEO / OG / JSON-LD / GA4', () => {
  for (const [lang, html] of [['pl', plHtml], ['en', enHtml]]) {
    assert.match(html, /<meta name="robots" content="noindex,nofollow">/, lang);
    assert.match(html, /<link rel="canonical" href="https:\/\/polskieradio\.cc\/aplikacje\//, lang);
    for (const alt of ['pl', 'en', 'x-default']) {
      assert.match(html, new RegExp(`hreflang="${alt}"`), `${lang} ${alt}`);
    }
    assert.match(html, /og-aplikacje-1200x630\.jpg/, lang);
    assert.match(html, /meta name="twitter:card" content="summary_large_image"/, lang);
    assert.match(html, /"@type":"MobileApplication"/, lang);
    assert.match(html, /gtag\('config','G-Y4EFTVBPE3'/, lang);
  }
});

test('pancerne reguły: brak Mission Control, brak martwych linków 404 Google Play, brak Font Awesome', () => {
  for (const [name, content] of [['pl', plHtml], ['en', enHtml], ['css', apCss], ['js', apJs], ['eco', apEcoJs]]) {
    assert.doesNotMatch(content, /Mission\s*Control/i, `${name}: zakaz Mission Control`);
    assert.doesNotMatch(content, /fkcjxp|yzkcjw/i, `${name}: zakaz wygasłych linków Google Play 404`);
    assert.doesNotMatch(content, /font-?awesome|cdnjs\.cloudflare\.com\/ajax\/libs\/font/i, `${name}: tylko czyste SVG`);
  }
  assert.ok(plHtml.includes(PLAY_APP_PL));
  assert.ok(plHtml.includes(PLAY_DEV_PL));
  assert.ok(enHtml.includes(PLAY_APP_EN));
  assert.ok(enHtml.includes(PLAY_DEV_EN));
});

test('uczciwość: zero fałszywego „LIVE” lub „na żywo”', () => {
  for (const [lang, html] of [['pl', plHtml], ['en', enHtml]]) {
    const visible = html.replace(/<script[\s\S]*?<\/script>/g, '').replace(/<[^>]+>/g, ' ');
    assert.doesNotMatch(visible, /\blive\b|na żywo|on air/i, `${lang}: bez fałszywego LIVE`);
  }
  for (const l of ['pl', 'en']) {
    const txt = eco.baseTicker(l).map((x) => `${x.b} ${x.t}`).join(' ') +
      eco.PROMOS.map((p) => `${p.k} ${p.kEn} ${p.h} ${p.hEn} ${p.p} ${p.pEn}`).join(' ');
    assert.doesNotMatch(txt, /\blive\b|na żywo|on air/i, `${l}: ticker/promo bez fałszywego LIVE`);
  }
});

test('standard cc-full-premium-www: logo .png, .header-right, ticker, Polecamy, Patronat i brak duplikatu back-to-top', () => {
  for (const [lang, html] of [['pl', plHtml], ['en', enHtml]]) {
    assert.match(html, /src="\/app-christian-culture\.png"/, lang);
    assert.doesNotMatch(html, /app-christian-culture\.webp/i, lang);
    assert.match(html, /class="header-right nav__actions"/, lang);
    assert.match(html, /id="apCanvas"/, lang);
    assert.match(html, /id="tickRun"/, lang);
    assert.match(html, /id="promoStage"/, lang);
    assert.match(html, /https:\/\/patronite\.pl\/osobowoscplus/, lang);
    assert.doesNotMatch(html, /id="backToTop"/i, `${lang}: cc-back-to-top.js sam renderuje przycisk`);
    for (const s of [
      '/js/cc-global-auth.js',
      '/js/cc-favorites.js',
      '/js/cc-mobile-edge.js',
      '/js/cc-edge-plus.js',
      '/components/cc-omni-search.js',
      '/components/cc-global-chat-button.js',
      '/js/cc-back-to-top.js',
      '/components/cc-support-footer.js'
    ]) {
      assert.match(html, new RegExp(`src="${s.replace(/\//g, '\\/')}(\\?[^"]*)?"[^>]*defer`), `${lang} ${s}`);
    }
  }
  assert.match(plHtml, /href="\/wspieraj"[^>]*>[\s\S]*?Wspieram to/);
  assert.match(enHtml, /href="\/wspieraj"[^>]*>[\s\S]*?Support this/);
  assert.doesNotMatch(apCss, /@media\s*\(prefers-reduced-motion:\s*reduce\)[^}]*animation\s*:\s*none/i);
});

test('wszystkie lokalne zasoby graficzne, CSS i JS istnieją na dysku', () => {
  const checked = new Set();
  for (const src of [plHtml, enHtml, apEcoJs]) {
    for (const m of src.matchAll(/(?:src|href|img|imgEn)"?\s*[:=]\s*["'](\/[^"'?#\s]+\.(?:png|jpe?g|webp|css|js))/gi)) {
      const rel = decodeURIComponent(m[1]).replace(/^\//, '');
      if (!checked.has(rel)) {
        checked.add(rel);
        assert.ok(fs.existsSync(path.join(ROOT, rel)), `Brak zasobu: ${rel}`);
      }
    }
  }
  assert.ok(checked.size >= 15, `Sprawdzono zbyt mało zasobów: ${checked.size}`);
});

test('allowlista wydania i routing _redirects dla /test/aplikacje/', () => {
  for (const f of [
    'test/aplikacje/index.html',
    'test/aplikacje/en/index.html',
    'test/aplikacje/ap.css',
    'test/aplikacje/ap.js',
    'test/aplikacje/ap-eco.js',
    'test/aplikacje/img/og-aplikacje-1200x630.jpg'
  ]) {
    assert.equal(isPublicFile(f), true, `isPublicFile(${f})`);
  }
  const redirects = read('_redirects');
  assert.match(redirects, /^\/test\/aplikacje \/test\/aplikacje\/index\.html 200$/m);
  assert.match(redirects, /^\/test\/aplikacje\/ \/test\/aplikacje\/index\.html 200$/m);
  assert.match(redirects, /^\/test\/aplikacje\/en \/test\/aplikacje\/en\/index\.html 200$/m);
  assert.match(redirects, /^\/test\/aplikacje\/en\/ \/test\/aplikacje\/en\/index\.html 200$/m);
});
