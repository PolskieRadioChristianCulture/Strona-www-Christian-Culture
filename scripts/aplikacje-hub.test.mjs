test('wszystkie lokalne zasoby graficzne, CSS i JS istnieją na dysku', () => {
  const checked = new Set();
  for (const src of [plHtml, enHtml, apEcoJs]) {
    for (const m of src.matchAll(/(?:src|href|img|imgEn)"?\s*[:=]\s*["'](\/[^"'?#\s]+\.(?:png|jpe?g|webp|css|js))/gi)) {
      const rel = decodeURIComponent(m[1]).replace(/^\//, '');
      if (!checked.has(rel)) {
        checked.add(rel);
        assert.ok(fs.existsSync(path.join(ROOT, rel)), `Brak zasobu: ${rel}`);
      }
    }
  }
  assert.ok(checked.size >= 15, `Sprawdzono zbyt mało zasobów: ${checked.size}`);
});

test('allowlista wydania, routing 200/301, indeks @w, sitemap, llms.txt i strona główna', () => {
  for (const f of [
    'aplikacje/index.html',
    'aplikacje/en/index.html',
    'aplikacje/ap.css',
    'aplikacje/ap.js',
    'aplikacje/ap-eco.js',
    'aplikacje/img/og-aplikacje-1200x630.jpg'
  ]) {
    assert.equal(isPublicFile(f), true, `isPublicFile(${f})`);
  }
  assert.equal(fs.existsSync(path.join(ROOT, 'test/aplikacje/index.html')), false, 'stary katalog test/aplikacje musi być usunięty');

  const redirects = read('_redirects');
  assert.match(redirects, /^\/aplikacje \/aplikacje\/index\.html 200$/m);
  assert.match(redirects, /^\/aplikacje\/ \/aplikacje\/index\.html 200$/m);
  assert.match(redirects, /^\/aplikacje\/en \/aplikacje\/en\/index\.html 200$/m);
  assert.match(redirects, /^\/aplikacje\/en\/ \/aplikacje\/en\/index\.html 200$/m);
  assert.match(redirects, /^\/apps \/aplikacje\/ 301$/m);
  assert.match(redirects, /^\/test\/aplikacje \/aplikacje\/ 301$/m);
  assert.match(redirects, /^\/test\/aplikacje\/ \/aplikacje\/ 301$/m);

  const indexHtml = read('index.html');
  assert.ok(indexHtml.includes('href="/aplikacje/"'), 'index.html musi linkować do /aplikacje/');

  const sitemap = read('sitemaps/pages.xml');
  assert.ok(sitemap.includes('https://polskieradio.cc/aplikacje/'));
  assert.ok(sitemap.includes('https://polskieradio.cc/aplikacje/en/'));

  const llms = read('llms.txt');
  assert.ok(llms.includes('https://polskieradio.cc/aplikacje/'));

  for (const idxPath of ['szukaj/catalog.json', 'data/cc-search-index.json']) {
    const data = JSON.parse(read(idxPath));
    const list = Array.isArray(data) ? data : (data.items || []);
    assert.ok(list.some((x) => x.url === 'https://polskieradio.cc/aplikacje/'), `${idxPath} PL`);
    assert.ok(list.some((x) => x.url === 'https://polskieradio.cc/aplikacje/en/'), `${idxPath} EN`);
  }

  const worker = read('_worker.js');
  assert.ok(worker.includes("decodedP === '/apps/en' || decodedP === '/test/aplikacje/en'"), '_worker.js /apps/en');
  assert.ok(worker.includes("decodedP === '/apps' || decodedP === '/test/aplikacje'"), '_worker.js /apps');
});

test('no-regression: pełna widoczność polskich znaków z ogonkami i descenderów (bez obcinania w H1/H2)', () => {
  const h1Match = apCss.match(/\.hero\s+h1\s*\{[^}]*\}/);
  assert.ok(h1Match, 'brak reguły .hero h1');
  assert.match(h1Match[0], /\/1\.(?:0[5-9]|[1-9]\d)/, 'line-height w .hero h1 musi wynosić >= 1.05');
  assert.match(apCss, /\.hero\.is-ready\s+h1\s+\.l\s*\{\s*overflow:\s*visible\b/);
  assert.match(apCss, /\.hero\s+h1\s+\.l\s*>\s*span\s*\{[^}]*padding:/);
  assert.match(apCss, /\.h2\s+em\s*\{[^}]*display:\s*inline-block;[^}]*padding:/);
});
