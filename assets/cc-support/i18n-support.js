const DYNAMIC_LOCALE_CACHE = new Map();

function findCanonicalLocaleKey(rawCode) {
  const clean = String(rawCode || 'pl').trim();
  if (!clean) return 'pl';
  if (Object.prototype.hasOwnProperty.call(SUPPORT_LOCALES, clean)) return clean;
  const lower = clean.toLowerCase();
  const keys = Object.keys(SUPPORT_LOCALES);
  const exactInsensitive = keys.find(k => k.toLowerCase() === lower);
  if (exactInsensitive) return exactInsensitive;
  const base = lower.split(/[-_]/)[0];
  const baseMatch = keys.find(k => k.toLowerCase() === base);
  return baseMatch || 'pl';
}

export function normalizeSupportLocale(rawCode) {
  return findCanonicalLocaleKey(rawCode);
}

export function registerSupportLocale(code, dictionary) {
  const key = String(code || '').trim();
  if (!key || !dictionary || typeof dictionary !== 'object') return false;
  SUPPORT_LOCALES[key] = { ...SUPPORT_LOCALES.pl, ...dictionary, code: dictionary.code || key };
  DYNAMIC_LOCALE_CACHE.set(key, SUPPORT_LOCALES[key]);
  return true;
}

export function getSupportDictionary(code) {
  const canonical = findCanonicalLocaleKey(code);
  return SUPPORT_LOCALES[canonical] || SUPPORT_LOCALES.pl;
}

export async function loadSupportLocale(code) {
  const clean = String(code || 'pl').trim();
  const canonical = findCanonicalLocaleKey(clean);
  if (DYNAMIC_LOCALE_CACHE.has(canonical)) return DYNAMIC_LOCALE_CACHE.get(canonical);
  if (typeof fetch === 'function') {
    const fileCode = encodeURIComponent(clean in SUPPORT_LOCALES ? clean : canonical);
    try {
      const res = await fetch('/assets/cc-support/locales/' + fileCode + '.json', {
        headers: { Accept: 'application/json' },
        cache: 'no-cache'
      });
      if (res.ok) {
        const json = await res.json();
        registerSupportLocale(canonical, json);
        return getSupportDictionary(canonical);
      }
    } catch (_) {
      // Fallback do lokalnego słownika synchronicznego
    }
  }
  return getSupportDictionary(canonical);
}

export function validateLocaleKeys(dictionaries = SUPPORT_LOCALES) {
  const codes = Object.keys(dictionaries || {});
  if (!codes.length || !dictionaries.pl) {
    return { ok: false, error: 'Missing base locale pl', details: {} };
  }
  const baseKeys = Object.keys(dictionaries.pl).sort();
  const details = {};
  let ok = true;
  for (const code of codes) {
    const dict = dictionaries[code] || {};
    const keys = Object.keys(dict).sort();
    const missing = baseKeys.filter(k => !keys.includes(k));
    const extra = keys.filter(k => !baseKeys.includes(k));
    const empty = keys.filter(k => typeof dict[k] === 'string' && dict[k].trim().length === 0);
    if (missing.length || extra.length || empty.length) ok = false;
    details[code] = { keyCount: keys.length, missing, extra, empty };
  }
  return { ok, baseKeyCount: baseKeys.length, details };
}
