export function registerSupportLocale(code, dictionary) {
  const normalized = String(code || '').toLowerCase().trim();
  if (!normalized || !dictionary || typeof dictionary !== 'object') return false;
  SUPPORT_LOCALES[normalized] = { ...SUPPORT_LOCALES.pl, ...dictionary, code: normalized };
  return true;
}

export function getSupportDictionary(code) {
  const normalized = String(code || 'pl').toLowerCase().slice(0, 2);
  return SUPPORT_LOCALES[normalized] || SUPPORT_LOCALES.pl;
}
