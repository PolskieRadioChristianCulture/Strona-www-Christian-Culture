const MAX_CACHE_ENTRIES = 16;
const assetCache = new Map();

const OT_BOOKS = new Set([
  'GEN', 'EXO', 'LEV', 'NUM', 'DEU', 'JOS', 'JDG', 'RUT', '1SA', '2SA',
  '1KI', '2KI', '1CH', '2CH', 'EZR', 'NEH', 'EST', 'JOB', 'PSA', 'PRO',
  'ECC', 'SNG', 'ISA', 'JER', 'LAM', 'EZK', 'DAN', 'HOS', 'JOL', 'AMO',
  'OBA', 'JON', 'MIC', 'NAM', 'HAB', 'ZEP', 'HAG', 'ZEC', 'MAL'
]);

const UNVERIFIED_EDITIONS = new Set(['BW', 'BT', 'BG']);

export function resetScholarToolsCache() {
  assetCache.clear();
}

function lruGet(key) {
  if (!assetCache.has(key)) return undefined;
  const val = assetCache.get(key);
  assetCache.delete(key);
  assetCache.set(key, val);
  return val;
}

function lruSet(key, val) {
  if (assetCache.has(key)) assetCache.delete(key);
  assetCache.set(key, val);
  if (assetCache.size > MAX_CACHE_ENTRIES) {
    const oldest = assetCache.keys().next().value;
    assetCache.delete(oldest);
  }
}

export function sanitizeDataAssetPath(relPath) {
  const clean = String(relPath || '').trim().replace(/^\/+/, '');
  if (!clean || clean.includes('\0') || clean.includes('\\') || clean.includes('..')) {
    return null;
  }
  if (!/^data\/bible(?:-scholar)?\/[A-Za-z0-9_./-]+\.json$/.test(clean)) {
    return null;
  }
  return clean;
}

export async function loadScholarAsset(relPath, env = {}, deps = {}) {
  const safePath = sanitizeDataAssetPath(relPath);
  if (!safePath) {
    throw new Error(`Invalid or blocked data asset path: ${String(relPath || '')}`);
  }
  const cached = lruGet(safePath);
  if (cached !== undefined) return cached;

  let parsed = null;
  if (typeof deps.fetchAsset === 'function') {
    parsed = await deps.fetchAsset(safePath);
  } else if (env?.ASSETS && typeof env.ASSETS.fetch === 'function') {
    const res = await env.ASSETS.fetch(new Request(`https://polskieradio.cc/${safePath}`));
    if (res && res.ok) {
      parsed = await res.json();
    }
  } else if (typeof process !== 'undefined' && process.versions?.node) {
    const [{ readFile }, pathMod] = await Promise.all([
      import('node:fs/promises'),
      import('node:path')
    ]);
    const full = pathMod.resolve(process.cwd(), safePath);
    const rootData = pathMod.resolve(process.cwd(), 'data');
    if (!full.startsWith(rootData + pathMod.sep)) {
      throw new Error('Asset path escaped data directory');
    }
    const raw = await readFile(full, 'utf8');
    parsed = JSON.parse(raw.replace(/^\uFEFF/, ''));
  }

  if (parsed !== null && parsed !== undefined) {
    lruSet(safePath, parsed);
  }
  return parsed || null;
}

function withProvenance(meta, payload) {
  return {
    ok: payload.ok !== false,
    datasetId: meta.datasetId,
    editionId: meta.editionId || meta.datasetId,
    sourceUrl: meta.sourceUrl,
    licenseId: meta.licenseId,
    reference: meta.reference || '',
    retrievedAt: new Date().toISOString(),
    uncertaintyNotice: meta.uncertaintyNotice || null,
    ...payload
  };
}

function resolveBookAndVerse({ reference = '', book = '', chapter = 0, verse = 0 } = {}) {
  if (reference) {
    const parsed = parseScriptureReference(reference);
    if (parsed) {
      return {
        book: parsed.bookId,
        chapter: parsed.chapter,
        verse: parsed.verse,
        endVerse: parsed.verseEnd || parsed.verse,
        reference: `${parsed.bookId} ${parsed.chapter}:${parsed.verse}${parsed.verseEnd > parsed.verse ? `-${parsed.verseEnd}` : ''}`
      };
    }
  }
  const bKey = normalizeText(book || '').replace(/\s+/g, ' ').trim();
  const resolvedBook = BOOK_ALIASES[bKey] || BOOK_ALIASES[bKey.replace(/\s+/g, '')] || String(book || '').trim().toUpperCase();
  const ch = Number.parseInt(chapter, 10) || 0;
  const v = Number.parseInt(verse, 10) || 0;
  if (!resolvedBook || ch <= 0) return null;
  return {
    book: resolvedBook,
    chapter: ch,
    verse: v,
    endVerse: v,
    reference: v > 0 ? `${resolvedBook} ${ch}:${v}` : `${resolvedBook} ${ch}`
  };
}

function classifyStrongId(strongId, entry = {}) {
  const m = /^([GH])0*(\d+)([a-z]?)$/i.exec(String(strongId || '').trim());
  if (!m) {
    return { strongTier: 'unknown', autoGenerated: Boolean(entry.autoGenerated), dir: 'ltr' };
  }
  const prefix = m[1].toUpperCase();
  const num = Number.parseInt(m[2], 10);
  const classicMax = prefix === 'G' ? 5624 : 8674;
  const isExtended = Boolean(entry.autoGenerated) || num > classicMax || num >= 21498;
  return {
    normalizedPrefix: prefix,
    strongTier: isExtended ? 'step_extended' : 'classic_strongs',
    autoGenerated: Boolean(entry.autoGenerated) || isExtended,
    dir: prefix === 'H' ? 'rtl' : 'ltr'
  };
}

function normalizeStrongCandidateIds(rawId) {
  const cleaned = String(rawId || '').trim().toUpperCase();
  const m = /^([GH])0*(\d+)([A-Z]?)$/.exec(cleaned);
  if (!m) return [cleaned].filter(Boolean);
  const [, prefix, digits, suffix] = m;
  const padded = `${prefix}${digits.padStart(4, '0')}${suffix.toLowerCase()}`;
  const unpadded = `${prefix}${Number.parseInt(digits, 10)}${suffix.toLowerCase()}`;
  return [...new Set([cleaned, padded, unpadded])];
}

function chapterAssetPath(bookId, chapterNum) {
  const chStr = chapterNum < 10 ? String(chapterNum).padStart(2, '0') : String(chapterNum);
  return `data/bible/${bookId}_${chStr}.json`;
}

function detectAramaicContext(bookId, chapterNum, verseNum, originalLang = '') {
  if (bookId === 'DAN' && ((chapterNum === 2 && verseNum >= 4) || (chapterNum >= 3 && chapterNum <= 7))) {
    return true;
  }
  if (bookId === 'EZR' && ((chapterNum === 4 && verseNum >= 8) || chapterNum === 5 || (chapterNum === 6 && verseNum <= 18) || (chapterNum === 7 && verseNum >= 12 && verseNum <= 26))) {
    return true;
  }
  if (bookId === 'JER' && chapterNum === 10 && verseNum === 11) {
    return true;
  }
  return /aramaic/i.test(originalLang) && false;
}

export async function ccBibleLexiconLookup(args = {}, env = {}, deps = {}) {
  const rawStrong = String(args.strongId || args.strong || '').trim();
  const rawQuery = String(args.query || args.lemma || '').trim().slice(0, 120);
  const limit = Math.min(25, Math.max(1, Number.parseInt(args.limit, 10) || 10));

  if (!rawStrong && !rawQuery) {
    return withProvenance({
      datasetId: 'step-mojabiblia-interlinear',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'CC-BY-4.0',
      uncertaintyNotice: 'Podaj strongId (np. G3056, H7225) lub query (np. logos, początek).'
    }, {
      ok: false,
      found: false,
      code: 'INVALID_QUERY',
      error: 'Wymagany parametr strongId lub query.'
    });
  }

  if (rawStrong) {
    const candidates = normalizeStrongCandidateIds(rawStrong);
    const prefix = rawStrong.trim().toUpperCase().startsWith('H') ? 'H' : 'G';
    const dict = await loadScholarAsset(`data/bible/lexicon/${prefix}.json`, env, deps).catch(() => null);
    let foundKey = null;
    let entry = null;
    if (dict) {
      for (const cand of candidates) {
        if (dict[cand]) {
          foundKey = cand;
          entry = dict[cand];
          break;
        }
      }
    }
    if (!entry) {
      return withProvenance({
        datasetId: 'step-mojabiblia-interlinear',
        sourceUrl: 'https://polskieradio.cc/mojabiblia',
        licenseId: 'CC-BY-4.0',
        reference: rawStrong,
        uncertaintyNotice: 'Nie odnaleziono kodu w leksykonie MojaBiblia.'
      }, {
        ok: false,
        found: false,
        code: 'LEXICON_ENTRY_NOT_FOUND',
        strongId: rawStrong
      });
    }

    const meta = classifyStrongId(foundKey, entry);
    return withProvenance({
      datasetId: 'step-mojabiblia-interlinear',
      editionId: meta.strongTier === 'step_extended' ? 'step-extended-lexicon' : 'mojabiblia-classic-strongs',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'CC-BY-4.0',
      reference: foundKey,
      uncertaintyNotice: meta.autoGenerated
        ? 'Wpis pochodzi z warstwy rozszerzonej STEP (autoGenerated) — nie należy do klasycznej numeracji Stronga G1-G5624/H1-H8674.'
        : null
    }, {
      found: true,
      entry: {
        strong: entry.strong || foundKey,
        original: entry.original || '',
        translit: entry.translit || '',
        pronunciation: entry.pronunciation || '',
        partOfSpeech: entry.partOfSpeech || '',
        definitionPl: entry.definitionPl || '',
        kjvDef: entry.kjvDef || '',
        origin: entry.origin || '',
        occurrences: entry.occurrences || null,
        keyVerses: Array.isArray(entry.keyVerses) ? entry.keyVerses.slice(0, 8) : [],
        strongTier: meta.strongTier,
        autoGenerated: meta.autoGenerated,
        dir: meta.dir
      }
    });
  }

  const normQ = normalizeText(rawQuery);
  const rawLower = rawQuery.toLowerCase();
  const [gDict, hDict] = await Promise.all([
    loadScholarAsset('data/bible/lexicon/G.json', env, deps).catch(() => ({})),
    loadScholarAsset('data/bible/lexicon/H.json', env, deps).catch(() => ({}))
  ]);
  const matches = [];
  for (const [id, item] of [...Object.entries(gDict || {}), ...Object.entries(hDict || {})]) {
    const hay = normalizeText(`${item.translit || ''} ${item.definitionPl || ''} ${item.kjvDef || ''} ${item.partOfSpeech || ''}`);
    const orig = String(item.original || '').toLowerCase();
    if (hay.includes(normQ) || orig.includes(rawLower)) {
      const meta = classifyStrongId(id, item);
      matches.push({
        strong: item.strong || id,
        original: item.original || '',
        translit: item.translit || '',
        definitionPl: item.definitionPl || '',
        strongTier: meta.strongTier,
        autoGenerated: meta.autoGenerated,
        dir: meta.dir
      });
      if (matches.length >= limit) break;
    }
  }

  return withProvenance({
    datasetId: 'step-mojabiblia-interlinear',
    sourceUrl: 'https://polskieradio.cc/mojabiblia',
    licenseId: 'CC-BY-4.0',
    reference: rawQuery,
    uncertaintyNotice: matches.some((m) => m.autoGenerated)
      ? 'Wyniki zawierają kody rozszerzone STEP oznaczone flagą autoGenerated: true.'
      : null
  }, {
    found: matches.length > 0,
    query: rawQuery,
    totalReturned: matches.length,
    items: matches
  });
}

export async function ccBibleTokenAnalysis(args = {}, env = {}, deps = {}) {
  const ref = resolveBookAndVerse(args);
  if (!ref || ref.verse <= 0) {
    return withProvenance({
      datasetId: 'step-mojabiblia-interlinear',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'CC-BY-4.0',
      uncertaintyNotice: 'Podaj pełną referencję księga rozdział:werset (np. J 1:1 lub DAN 2:4).'
    }, {
      ok: false,
      found: false,
      code: 'INVALID_REFERENCE',
      error: 'Nieprawidłowe lub niepełne odniesienie biblijne.'
    });
  }

  const chapterData = await loadScholarAsset(chapterAssetPath(ref.book, ref.chapter), env, deps).catch(() => null);
  const verseObj = chapterData?.verses?.find((x) => Number(x.verse) === ref.verse) || null;
  if (!chapterData || !verseObj) {
    return withProvenance({
      datasetId: 'step-mojabiblia-interlinear',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'CC-BY-4.0',
      reference: ref.reference,
      uncertaintyNotice: `Odniesienie ${ref.reference} nie istnieje w kanonie rozdziałów MojaBiblia / UBG.`
    }, {
      ok: false,
      found: false,
      code: 'VERSE_NOT_FOUND',
      error: `Nie znaleziono wersetu ${ref.reference}.`
    });
  }

  const isAramaic = detectAramaicContext(ref.book, ref.chapter, ref.verse, chapterData.originalLang);
  const originalLanguage = ref.book && OT_BOOKS.has(ref.book)
    ? (isAramaic ? 'Aramaic' : (chapterData.originalLang || 'Hebrew'))
    : 'Greek';
  const dir = OT_BOOKS.has(ref.book) ? 'rtl' : 'ltr';
  const glosy = await loadScholarAsset('data/bible/glosy-pl.json', env, deps).catch(() => ({}));

  const tokens = (verseObj.interlinear || []).map((t, index) => {
    const strongMeta = classifyStrongId(t.strong, {});
    return {
      position: index + 1,
      original: t.original || '',
      translit: t.translit || '',
      strong: t.strong || '',
      strongTier: strongMeta.strongTier,
      autoGenerated: strongMeta.autoGenerated,
      morphology: t.morph || t.morphology || '',
      glossPl: t.glossPl || t.pl || (t.strong ? glosy[t.strong] : '') || t.en || '',
      dir: t.dir || dir
    };
  });

  return withProvenance({
    datasetId: 'step-mojabiblia-interlinear',
    sourceUrl: `https://polskieradio.cc/mojabiblia?book=${ref.book}&chapter=${ref.chapter}&verse=${ref.verse}&mode=interlinear`,
    licenseId: 'CC-BY-4.0',
    reference: ref.reference,
    uncertaintyNotice: tokens.some((t) => t.autoGenerated)
      ? 'Wykryto rozszerzone kody STEP (autoGenerated: true), oddzielone od klasycznych kodów Stronga.'
      : null
  }, {
    found: true,
    book: ref.book,
    bookName: chapterData.bookName || ref.book,
    chapter: ref.chapter,
    verse: ref.verse,
    textUbg: verseObj.text?.UBG || '',
    originalLanguage,
    isAramaicSection: isAramaic,
    dir,
    tokensCount: tokens.length,
    tokens
  });
}

export async function ccBibleCrossReferences(args = {}, env = {}, deps = {}) {
  const ref = resolveBookAndVerse(args);
  const limit = Math.min(50, Math.max(1, Number.parseInt(args.limit, 10) || 15));
  const offset = Math.max(0, Number.parseInt(args.cursor, 10) || 0);

  if (!ref || ref.verse <= 0) {
    return withProvenance({
      datasetId: 'openbible-cross-references',
      sourceUrl: 'https://www.openbible.info/labs/cross-references/',
      licenseId: 'CC-BY-4.0',
      uncertaintyNotice: 'Podaj pełne odniesienie z numerem wersetu (np. J 3:16).'
    }, {
      ok: false,
      found: false,
      code: 'INVALID_REFERENCE',
      error: 'Wymagane odniesienie księga rozdział:werset.'
    });
  }

  const shard = await loadScholarAsset(`data/bible-scholar/xrefs/${ref.book}.json`, env, deps).catch(() => null);
  const key = `${ref.chapter}:${ref.verse}`;
  const rawList = shard?.refs?.[key] || null;
  if (!shard || !Array.isArray(rawList) || !rawList.length) {
    return withProvenance({
      datasetId: 'openbible-cross-references',
      sourceUrl: 'https://www.openbible.info/labs/cross-references/',
      licenseId: 'CC-BY-4.0',
      reference: ref.reference,
      uncertaintyNotice: `Brak odsyłaczy w OpenBible dla ${ref.reference} lub odniesienie wykracza poza zbiór kanoniczny.`
    }, {
      found: false,
      reference: ref.reference,
      totalCount: 0,
      items: []
    });
  }

  const slice = rawList.slice(offset, offset + limit).map(([targetRef, votes]) => ({
    targetRef,
    votes
  }));
  const nextCursor = offset + slice.length < rawList.length ? String(offset + slice.length) : null;

  return withProvenance({
    datasetId: 'openbible-cross-references',
    sourceUrl: 'https://www.openbible.info/labs/cross-references/',
    licenseId: 'CC-BY-4.0',
    reference: ref.reference
  }, {
    found: true,
    totalCount: rawList.length,
    returnedCount: slice.length,
    nextCursor,
    attribution: 'OpenBible.info Cross References (CC BY 4.0)',
    items: slice
  });
}

export async function ccBibleConcordance(args = {}, env = {}, deps = {}) {
  const query = String(args.query || '').trim().slice(0, 80);
  const bookFilter = String(args.book || '').trim().toUpperCase();
  const testamentFilter = String(args.testament || '').trim().toLowerCase();
  const limit = Math.min(50, Math.max(1, Number.parseInt(args.limit, 10) || 15));
  const offset = Math.max(0, Number.parseInt(args.cursor, 10) || 0);

  if (query.length < 2) {
    return withProvenance({
      datasetId: 'ubg-2025',
      sourceUrl: 'https://polskieradio.cc/sba',
      licenseId: 'CC-BY-ND-4.0 / Fundacja Wrota Nadziei',
      uncertaintyNotice: 'Zapytanie konkordancji musi mieć co najmniej 2 znaki.'
    }, {
      ok: false,
      found: false,
      code: 'QUERY_TOO_SHORT',
      error: 'Podaj co najmniej 2 znaki do przeszukania tekstu UBG.'
    });
  }

  const data = await loadScholarAsset('data/bible/szukaj-ubg.json', env, deps).catch(() => null);
  if (!data || !Array.isArray(data.r) || !Array.isArray(data.b)) {
    return withProvenance({
      datasetId: 'ubg-2025',
      sourceUrl: 'https://polskieradio.cc/sba',
      licenseId: 'CC-BY-ND-4.0 / Fundacja Wrota Nadziei',
      uncertaintyNotice: 'Baza konkordancji UBG jest tymczasowo niedostępna.'
    }, {
      ok: false,
      found: false,
      code: 'DATASET_UNAVAILABLE',
      error: 'Brak pliku szukaj-ubg.json.'
    });
  }

  const normQ = normalizeText(query);
  const matches = [];
  for (const row of data.r) {
    const bookCode = data.b[row[0]];
    if (bookFilter && bookCode !== bookFilter) continue;
    if (testamentFilter === 'ot' && !OT_BOOKS.has(bookCode)) continue;
    if (testamentFilter === 'nt' && OT_BOOKS.has(bookCode)) continue;
    const text = row[3] || '';
    if (normalizeText(text).includes(normQ)) {
      matches.push({
        reference: `${bookCode} ${row[1]}:${row[2]}`,
        book: bookCode,
        chapter: row[1],
        verse: row[2],
        text,
        translation: 'UBG'
      });
    }
  }

  const page = matches.slice(offset, offset + limit);
  const nextCursor = offset + page.length < matches.length ? String(offset + page.length) : null;

  return withProvenance({
    datasetId: 'ubg-2025',
    editionId: 'UBG',
    sourceUrl: 'https://polskieradio.cc/sba',
    licenseId: 'CC-BY-ND-4.0 / Fundacja Wrota Nadziei',
    reference: query
  }, {
    found: matches.length > 0,
    query,
    translation: 'UBG',
    totalCount: matches.length,
    returnedCount: page.length,
    nextCursor,
    items: page
  });
}

export async function ccBibleCompareEditions(args = {}, env = {}, deps = {}) {
  const ref = resolveBookAndVerse(args);
  const requested = Array.isArray(args.editions) && args.editions.length
    ? args.editions.map((e) => String(e || '').trim().toUpperCase())
    : ['UBG', 'ORIGINAL'];

  const blockedEditions = [];
  for (const ed of requested) {
    if (UNVERIFIED_EDITIONS.has(ed)) {
      blockedEditions.push({
        edition: ed,
        code: 'LICENSE_BLOCKED',
        reason: `Przekład ${ed} jest wstrzymany przez bramkę licencyjną (audyt 2026-11-28 wykazał duplikat UBG bez praw do emisji ${ed}).`
      });
    }
  }

  if (requested.every((ed) => UNVERIFIED_EDITIONS.has(ed))) {
    return withProvenance({
      datasetId: 'mojabiblia-bw-bt-bg-embedded',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'BLOCKED_UNVERIFIED_DUPLICATE',
      reference: ref?.reference || String(args.reference || ''),
      uncertaintyNotice: 'Żaden z żądanych przekładów nie jest zatwierdzony licencyjnie. Użyj kanonicznego UBG lub warstwy oryginału.'
    }, {
      ok: false,
      blocked: true,
      code: 'LICENSE_BLOCKED',
      blockedEditions
    });
  }

  if (!ref || ref.verse <= 0) {
    return withProvenance({
      datasetId: 'ubg-2025',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'CC-BY-ND-4.0 / Fundacja Wrota Nadziei',
      uncertaintyNotice: 'Podaj poprawne odniesienie księga rozdział:werset.'
    }, {
      ok: false,
      found: false,
      code: 'INVALID_REFERENCE'
    });
  }

  const chapterData = await loadScholarAsset(chapterAssetPath(ref.book, ref.chapter), env, deps).catch(() => null);
  const verseObj = chapterData?.verses?.find((x) => Number(x.verse) === ref.verse) || null;
  if (!verseObj) {
    return withProvenance({
      datasetId: 'ubg-2025',
      sourceUrl: 'https://polskieradio.cc/mojabiblia',
      licenseId: 'CC-BY-ND-4.0 / Fundacja Wrota Nadziei',
      reference: ref.reference,
      uncertaintyNotice: `Werset ${ref.reference} nie występuje w tym podziale rozdziałów/wersetów UBG (np. różnice numeracji Psalmów).`
    }, {
      ok: false,
      found: false,
      code: 'VERSE_NOT_FOUND',
      blockedEditions
    });
  }

  const editions = {};
  if (requested.includes('UBG') || !blockedEditions.length) {
    editions.UBG = {
      text: verseObj.text?.UBG || '',
      licenseId: 'CC-BY-ND-4.0 / Fundacja Wrota Nadziei',
      verified: true
    };
  }
  if (requested.includes('ORIGINAL')) {
    editions.ORIGINAL = {
      language: chapterData.originalLang || (OT_BOOKS.has(ref.book) ? 'Hebrew' : 'Greek'),
      dir: OT_BOOKS.has(ref.book) ? 'rtl' : 'ltr',
      text: (verseObj.interlinear || []).map((t) => t.original).filter(Boolean).join(' '),
      transliteration: (verseObj.interlinear || []).map((t) => t.translit).filter(Boolean).join(' '),
      licenseId: 'CC-BY-4.0'
    };
  }

  return withProvenance({
    datasetId: 'ubg-2025',
    editionId: 'UBG',
    sourceUrl: `https://polskieradio.cc/mojabiblia?book=${ref.book}&chapter=${ref.chapter}&verse=${ref.verse}`,
    licenseId: 'CC-BY-ND-4.0 + CC-BY-4.0',
    reference: ref.reference,
    uncertaintyNotice: blockedEditions.length
      ? `Pominięto niezweryfikowane przekłady: ${blockedEditions.map((b) => b.edition).join(', ')}.`
      : null
  }, {
    found: true,
    reference: ref.reference,
    editions,
    blockedEditions
  });
}

